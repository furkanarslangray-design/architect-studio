import YAML from "yaml";
import type { ArchState } from "../../core/src/state";
import { nodesOfKind, pascalCase, uniqueSlugs } from "./util";

export function generateOpenAPI31(state: ArchState): string {
  const services = nodesOfKind(state, "service");
  const slugs = uniqueSlugs(services);
  const paths: Record<string, unknown> = {};
  const schemas: Record<string, unknown> = {
    Health: {
      type: "object",
      properties: { status: { type: "string", examples: ["ok"] } },
      required: ["status"],
    },
  };

  for (const service of services) {
    const slug = slugs.get(service.id)!;
    const model = `${pascalCase(service.name)}Item`;
    schemas[model] = {
      type: "object",
      properties: {
        id: { type: "string" },
        name: { type: "string" },
      },
      required: ["id", "name"],
    };

    paths[`/${slug}/health`] = {
      get: {
        operationId: `get_${slug.replace(/-/g, "_")}_health`,
        summary: `Health check for ${service.name}`,
        responses: {
          "200": {
            description: "Service is healthy",
            content: { "application/json": { schema: { $ref: "#/components/schemas/Health" } } },
          },
        },
      },
    };

    paths[`/api/${slug}`] = {
      get: {
        operationId: `list_${slug.replace(/-/g, "_")}`,
        summary: `List ${service.name} resources`,
        responses: {
          "200": {
            description: "A list of resources",
            content: {
              "application/json": {
                schema: { type: "array", items: { $ref: `#/components/schemas/${model}` } },
              },
            },
          },
        },
      },
      post: {
        operationId: `create_${slug.replace(/-/g, "_")}`,
        summary: `Create a ${service.name} resource`,
        requestBody: {
          required: true,
          content: { "application/json": { schema: { $ref: `#/components/schemas/${model}` } } },
        },
        responses: {
          "201": {
            description: "Created",
            content: { "application/json": { schema: { $ref: `#/components/schemas/${model}` } } },
          },
          "400": { description: "Invalid request" },
        },
      },
    };
  }

  return YAML.stringify(
    {
      openapi: "3.1.0",
      info: {
        title: "Generated Architecture API",
        version: "1.0.0",
        description: "Generated by AI Principal Architect",
      },
      servers: [{ url: "http://localhost:3000" }],
      paths,
      components: { schemas },
    },
    { lineWidth: 0 },
  );
}
