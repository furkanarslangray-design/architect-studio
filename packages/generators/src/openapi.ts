import YAML from "yaml";
import type { ArchState, Entity } from "../../core/src/state";
import {
  entitiesForService,
  openapiFieldSchema,
  pascalCase,
  uniqueEntitySlugs,
  uniqueName,
  uniqueSlugs,
} from "./util";

interface OperationContext {
  serviceSlug: string;
  modelName: string;
  entitySlug?: string;
}

export function generateOpenAPI31(state: ArchState): string {
  const services = state.nodes.filter((node) => node.kind === "service");
  const slugs = uniqueSlugs(services);
  const paths: Record<string, unknown> = {};
  const schemaNames = new Set<string>(["Health", "Error"]);
  const schemas: Record<string, unknown> = {
    Health: {
      type: "object",
      properties: { status: { type: "string", examples: ["ok"] } },
      required: ["status"],
    },
    Error: {
      type: "object",
      properties: {
        error: { type: "string" },
        code: { type: "string" },
      },
      required: ["error"],
    },
  };

  const entityModels = new Map<string, string>();
  for (const entity of state.entities) {
    entityModels.set(entity.id, uniqueName(pascalCase(entity.name), schemaNames));
  }
  for (const entity of state.entities) {
    schemas[entityModels.get(entity.id)!] = entitySchema(entity);
  }

  for (const service of services) {
    const serviceSlug = slugs.get(service.id)!;
    const ownedEntities = entitiesForService(state, service.id);
    const entitySlugs = uniqueEntitySlugs(ownedEntities);

    paths[`/${serviceSlug}/health`] = {
      get: {
        operationId: operationId("get", serviceSlug, "health"),
        summary: `Health check for ${service.name}`,
        tags: [serviceSlug],
        responses: {
          "200": {
            description: "Service is healthy",
            content: { "application/json": { schema: { $ref: "#/components/schemas/Health" } } },
          },
        },
      },
    };

    if (ownedEntities.length > 0) {
      for (const entity of ownedEntities) {
        addEntityRoutes(paths, {
          serviceSlug,
          modelName: entityModels.get(entity.id)!,
          entitySlug: entitySlugs.get(entity.id)!,
          tag: serviceSlug,
        });
      }
      continue;
    }

    const fallbackModel = uniqueName(`${pascalCase(service.name)}Item`, schemaNames);
    schemas[fallbackModel] = {
      type: "object",
      properties: {
        id: { type: "string" },
        name: { type: "string" },
      },
      required: ["id", "name"],
    };
    addEntityRoutes(paths, {
      serviceSlug,
      modelName: fallbackModel,
      aliasPath: `/api/${serviceSlug}`,
      tag: serviceSlug,
    });
  }

  return YAML.stringify(
    {
      openapi: "3.1.0",
      info: {
        title: "Generated Architecture API",
        version: "1.0.0",
        description: "Generated by AI Principal Architect from the architecture state.",
      },
      servers: [{ url: "http://localhost:3000", description: "Local development" }],
      tags: services.map((service) => ({ name: slugs.get(service.id)!, description: service.name })),
      paths,
      components: { schemas },
    },
    { lineWidth: 0 },
  );
}

function addEntityRoutes(
  paths: Record<string, unknown>,
  context: OperationContext & { aliasPath?: string; tag: string },
): void {
  const collectionPath = context.aliasPath ?? `/api/${context.serviceSlug}/${context.entitySlug}`;
  const itemPath = `${collectionPath}/{id}`;
  const operationBase = [context.serviceSlug, context.entitySlug].filter(Boolean).join("_");
  const modelRef = { $ref: `#/components/schemas/${context.modelName}` };
  const idParam = {
    name: "id",
    in: "path",
    required: true,
    schema: { type: "string" },
  };

  paths[collectionPath] = {
    get: {
      operationId: operationId("list", operationBase),
      summary: `List ${context.modelName} resources`,
      tags: [context.tag],
      parameters: [
        { name: "limit", in: "query", schema: { type: "integer", minimum: 1, maximum: 100, default: 20 } },
        { name: "offset", in: "query", schema: { type: "integer", minimum: 0, default: 0 } },
      ],
      responses: {
        "200": {
          description: "A page of resources",
          content: {
            "application/json": {
              schema: { type: "array", items: modelRef },
            },
          },
        },
        "400": errorResponse("Invalid pagination parameters"),
      },
    },
    post: {
      operationId: operationId("create", operationBase),
      summary: `Create a ${context.modelName} resource`,
      tags: [context.tag],
      requestBody: {
        required: true,
        content: { "application/json": { schema: modelRef } },
      },
      responses: {
        "201": {
          description: "Created",
          content: { "application/json": { schema: modelRef } },
        },
        "400": errorResponse("Invalid request body"),
      },
    },
  };

  paths[itemPath] = {
    get: {
      operationId: operationId("get", operationBase, "by_id"),
      summary: `Get one ${context.modelName} resource`,
      tags: [context.tag],
      parameters: [idParam],
      responses: {
        "200": {
          description: "The resource",
          content: { "application/json": { schema: modelRef } },
        },
        "404": errorResponse("Resource not found"),
      },
    },
    patch: {
      operationId: operationId("update", operationBase, "by_id"),
      summary: `Update one ${context.modelName} resource`,
      tags: [context.tag],
      parameters: [idParam],
      requestBody: {
        required: true,
        content: { "application/json": { schema: modelRef } },
      },
      responses: {
        "200": {
          description: "Updated resource",
          content: { "application/json": { schema: modelRef } },
        },
        "404": errorResponse("Resource not found"),
      },
    },
    delete: {
      operationId: operationId("delete", operationBase, "by_id"),
      summary: `Delete one ${context.modelName} resource`,
      tags: [context.tag],
      parameters: [idParam],
      responses: {
        "204": { description: "Deleted" },
        "404": errorResponse("Resource not found"),
      },
    },
  };
}

function entitySchema(entity: Entity): Record<string, unknown> {
  const properties: Record<string, unknown> = {};
  const required: string[] = [];
  for (const field of entity.fields) {
    properties[field.name] = {
      ...openapiFieldSchema(field),
      ...(field.description ? { description: field.description } : {}),
      ...(field.primary ? { readOnly: true } : {}),
    };
    if (field.required || field.primary) required.push(field.name);
  }
  return {
    type: "object",
    description: entity.description || `${entity.name} domain object`,
    properties,
    ...(required.length > 0 ? { required } : {}),
  };
}

function errorResponse(description: string): unknown {
  return {
    description,
    content: { "application/json": { schema: { $ref: "#/components/schemas/Error" } } },
  };
}

function operationId(...parts: string[]): string {
  return parts
    .join("_")
    .toLowerCase()
    .replace(/[^a-z0-9_]+/g, "_")
    .replace(/^_+|_+$/g, "");
}
