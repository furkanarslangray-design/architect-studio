import YAML from "yaml";
import type { ArchState } from "../../core/src/state";
import { nodesOfKind, pascalCase, uniqueName, uniqueSlugs } from "./util";

export function generateAsyncAPI(state: ArchState): string {
  const queues = nodesOfKind(state, "queue");
  const slugs = uniqueSlugs(queues);
  const channels: Record<string, unknown> = {};
  const messageNames = new Set<string>(["DomainEvent"]);
  const messageByQueue = new Map<string, string>();
  for (const queue of queues) {
    messageByQueue.set(queue.id, uniqueName(`${pascalCase(queue.name)}Event`, messageNames));
  }

  for (const queue of queues) {
    const slug = slugs.get(queue.id)!;
    const message = messageByQueue.get(queue.id)!;
    channels[slug] = {
      description: `${queue.name} channel (${String(queue.props.engine ?? "generic")})`,
      publish: {
        operationId: `publish_${slug.replace(/-/g, "_")}`,
        summary: `Publish a ${message}`,
        message: { $ref: `#/components/messages/${message}` },
      },
      subscribe: {
        operationId: `consume_${slug.replace(/-/g, "_")}`,
        summary: `Consume ${message} messages`,
        message: { $ref: `#/components/messages/${message}` },
      },
    };
  }

  const messages: Record<string, unknown> = {
    DomainEvent: {
      name: "DomainEvent",
      title: "Envelope shared by all domain events",
      contentType: "application/json",
      payload: { $ref: "#/components/schemas/DomainEvent" },
    },
  };
  for (const queue of queues) {
    const slug = slugs.get(queue.id)!;
    const message = messageByQueue.get(queue.id)!;
    messages[message] = {
      name: message,
      title: `${queue.name} event`,
      contentType: "application/json",
      payload: { $ref: "#/components/schemas/DomainEvent" },
      examples: [{ headers: { "x-event-type": slug }, payload: { id: "evt-1", type: slug } }],
    };
  }

  return YAML.stringify(
    {
      asyncapi: "2.6.0",
      info: {
        title: "Generated Architecture Events",
        version: "1.0.0",
        description: "Generated by AI Principal Architect from the architecture state.",
      },
      defaultContentType: "application/json",
      servers: {
        production: {
          url: "events://broker",
          protocol: "redis",
          description: "Event broker declared by the architecture",
        },
      },
      channels,
      components: {
        messages,
        schemas: {
          DomainEvent: {
            type: "object",
            properties: {
              id: { type: "string" },
              type: { type: "string" },
              occurredAt: { type: "string", format: "date-time" },
              payload: { type: "object", additionalProperties: true },
            },
            required: ["id", "type"],
          },
        },
      },
    },
    { lineWidth: 0 },
  );
}
