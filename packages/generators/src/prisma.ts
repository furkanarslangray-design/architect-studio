import type { ArchNode, ArchState, Entity, EntityField } from "../../core/src/state";
import { slugify } from "../../core/src/ids";
import {
  camelCase,
  entitiesForDatabase,
  nodesOfKind,
  pascalCase,
  prismaFieldType,
  prismaProviderFor,
  uniqueName,
} from "./util";

export function generatePrisma(state: ArchState): string {
  const databases = nodesOfKind(state, "database");
  const provider = prismaProviderFor(databases[0]);
  const engines = [...new Set(databases.map((database) => String(database.props.engine ?? "postgres")))];
  const usedModels = new Set<string>();
  const usedMaps = new Set<string>();

  const blocks: string[] = [];
  for (const database of databases) {
    const model = uniqueName(pascalCase(database.name), usedModels);
    const map = uniqueName(slugify(database.name), usedMaps);
    blocks.push(
      [
        `/// ${database.name} (${slugify(database.name)})`,
        `model ${model} {`,
        "  id        String   @id @default(cuid())",
        "  name      String",
        "  createdAt DateTime @default(now())",
        "  updatedAt DateTime @updatedAt",
        "",
        `  @@map("${map}")`,
        "}",
      ].join("\n"),
    );
  }

  const entityById = new Map(state.entities.map((entity) => [entity.id, entity]));
  for (const entity of state.entities) {
    blocks.push(entityModel(entity, usedModels, usedMaps, entityById));
  }

  const header = [
    "// Generated by AI Principal Architect",
    `// Datasource provider derived from the architecture state: ${provider}`,
    ...(engines.length > 1
      ? [`// Multiple datastore engines were declared (${engines.join(", ")}); the first one is used as the Prisma provider.`]
      : []),
    "",
  ];

  return [
    ...header,
    "generator client {",
    '  provider = "prisma-client-js"',
    "}",
    "",
    "datasource db {",
    `  provider = "${provider}"`,
    '  url      = env("DATABASE_URL")',
    "}",
    "",
    ...blocks,
    "",
  ].join("\n");
}

function entityModel(
  entity: Entity,
  usedModels: Set<string>,
  usedMaps: Set<string>,
  entityById: Map<string, Entity>,
): string {
  const model = uniqueName(pascalCase(entity.name), usedModels);
  const map = uniqueName(slugify(entity.name), usedMaps);
  const fields: EntityField[] = entity.fields.map((field) => ({ ...field }));

  let primary = fields.find((field) => field.primary);
  if (!primary) {
    const idField = fields.find((field) => field.name.toLowerCase() === "id");
    if (idField) {
      idField.primary = true;
      primary = idField;
    } else {
      const generated: EntityField = {
        name: "id",
        type: "uuid",
        required: true,
        unique: false,
        primary: true,
      };
      fields.unshift(generated);
      primary = generated;
    }
  }

  const relationColumns: Array<{ field: string; index: boolean }> = [];
  for (const relation of entity.relations) {
    const target = entityById.get(relation.target);
    if (!target) continue;
    const fieldName = relation.field ?? `${camelCase(target.name)}Id`;
    if (fields.some((field) => field.name === fieldName)) continue;
    relationColumns.push({ field: fieldName, index: true });
  }

  const lines = fields.map((field) => fieldLine(field, field === primary, field.type));
  for (const column of relationColumns) {
    lines.push(`${column.field} String?`);
  }

  const indexes = relationColumns
    .filter((column) => column.index)
    .map((column) => `  @@index([${column.field}])`);

  return [
    `/// ${entity.name}${entity.description ? ` — ${entity.description}` : ""}`,
    `model ${model} {`,
    ...lines,
    "",
    ...indexes,
    ...(indexes.length > 0 ? [""] : []),
    `  @@map("${map}")`,
    "}",
  ].join("\n");
}

function fieldLine(field: EntityField, isPrimary: boolean, type: EntityField["type"]): string {
  const attrs: string[] = [];
  if (isPrimary) {
    attrs.push("@id");
    attrs.push(type === "int" ? "@default(autoincrement())" : "@default(cuid())");
  }
  if (field.unique && !isPrimary) attrs.push("@unique");
  if (!isPrimary && field.type === "datetime" && field.name === "createdAt") attrs.push("@default(now())");
  if (!isPrimary && field.type === "datetime" && field.name === "updatedAt") attrs.push("@updatedAt");

  const optional = field.required || isPrimary ? "" : "?";
  const padding = " ".repeat(Math.max(1, 12 - field.name.length));
  const typePadding = " ".repeat(Math.max(1, 9 - prismaFieldType(field).length));
  return `  ${field.name}${padding}${prismaFieldType(field)}${optional}${typePadding}${attrs.join(" ")}`.trimEnd();
}

export function prismaModelsForDatabase(state: ArchState, database: ArchNode): Entity[] {
  return entitiesForDatabase(state, database.id);
}
