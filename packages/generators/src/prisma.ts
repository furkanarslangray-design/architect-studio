import type { ArchState } from "../../core/src/state";
import { nodesOfKind, pascalCase, uniqueSlugs } from "./util";

export function generatePrisma(state: ArchState): string {
  const databases = nodesOfKind(state, "database");
  const slugs = uniqueSlugs(databases);
  const usedModels = new Set<string>();
  const models = databases.map((database) => {
    const slug = slugs.get(database.id)!;
    let model = pascalCase(database.name);
    let counter = 2;
    while (usedModels.has(model)) {
      model = `${pascalCase(database.name)}${counter}`;
      counter += 1;
    }
    usedModels.add(model);
    return [
      `/// ${database.name} (${slug})`,
      `model ${model} {`,
      "  id        String   @id @default(cuid())",
      "  name      String",
      "  createdAt DateTime @default(now())",
      "  updatedAt DateTime @updatedAt",
      "",
      `  @@map("${slug}")`,
      "}",
    ].join("\n");
  });

  return [
    "// Generated by AI Principal Architect",
    "",
    "generator client {",
    '  provider = "prisma-client-js"',
    "}",
    "",
    "datasource db {",
    '  provider = "postgresql"',
    '  url      = env("DATABASE_URL")',
    "}",
    "",
    ...models,
    "",
  ].join("\n");
}
