import type { MetricReport } from "../../core/src/metrics";
import type { ValidationReport } from "../../validators/src";

export interface ManifestSummary {
  components?: number;
  entities?: number;
  tasks?: number;
  waves?: number;
  validation?: ValidationReport;
}

export function renderManifest(
  files: Record<string, string>,
  metrics: MetricReport[],
  summary: ManifestSummary = {},
): string {
  const paths = Object.keys(files).sort();
  const failed = metrics.filter((metric) => !metric.pass);
  const taskFiles = paths.filter((path) => path.startsWith("tasks/"));
  const validation = summary.validation;

  return [
    "# Package Manifest",
    "",
    "Generated by AI Principal Architect.",
    "",
    "## Overview",
    "",
    `- Components: ${summary.components ?? "-"}`,
    `- Domain entities: ${summary.entities ?? "-"}`,
    `- Task packets: ${summary.tasks ?? taskFiles.length}`,
    `- Execution waves: ${summary.waves ?? "-"}`,
    `- Validation: ${validation ? (validation.ok ? "passed" : "failed") : "-"}`,
    "",
    "## Contents",
    "",
    ...paths.map((path) => `- \`${path}\``),
    "",
    "## Task packets",
    "",
    ...(taskFiles.length > 0 ? taskFiles.map((path) => `- \`${path}\``) : ["- No task packets."]),
    "",
    "## Metrics",
    "",
    "| Metric | Value | Target | Pass |",
    "|---|---|---|---|",
    ...metrics.map((metric) => `| ${metric.name} | ${metric.value} | ${metric.target} | ${metric.pass ? "yes" : "no"} |`),
    "",
    failed.length === 0
      ? "All output metrics passed."
      : `${failed.length} metric(s) are outside target: ${failed.map((metric) => metric.name).join(", ")}.`,
    "",
    ...(validation && validation.issues.length > 0
      ? [
          "## Validation issues",
          "",
          ...validation.issues.map((issue) => `- \`${issue.file}\`: ${issue.message}`),
          "",
        ]
      : []),
    "## Reproduce",
    "",
    "```bash",
    `# Deterministic validation: ${validation?.checksRun ?? 0} checks across ${validation?.artifactsValidated.length ?? 0} artifact kinds`,
    "pnpm test",
    "```",
    "",
  ].join("\n");
}
