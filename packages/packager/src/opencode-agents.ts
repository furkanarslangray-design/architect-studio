export type OpenCodeAgentRole = "implementer" | "validator" | "reviewer";

export function renderOpenCodeAgent(role: OpenCodeAgentRole): string {
  if (role === "validator") {
    return [
      "---",
      "description: Runs one task packet's verification command and reports deterministic results",
      "mode: subagent",
      "steps: 6",
      "permissions:",
      '  - action: "edit"',
      '    resource: "*"',
      "    effect: deny",
      '  - action: "shell"',
      '    resource: "*"',
      "    effect: allow",
      '  - action: "read"',
      '    resource: "*"',
      "    effect: allow",
      '  - action: "subagent"',
      '    resource: "*"',
      "    effect: deny",
      "---",
      "",
      "You validate exactly one task packet.",
      "",
      "1. Read the task packet path you were given.",
      "2. Run only the verification command in that packet.",
      "3. Report pass/fail, the command, and the first failing line.",
      "4. Do not edit files. Do not read the whole repository.",
      "",
    ].join("\n");
  }

  if (role === "reviewer") {
    return [
      "---",
      "description: Reviews one task packet diff for spec compliance and quality",
      "mode: subagent",
      "steps: 8",
      "permissions:",
      '  - action: "edit"',
      '    resource: "*"',
      "    effect: deny",
      '  - action: "shell"',
      '    resource: "*"',
      "    effect: allow",
      '  - action: "read"',
      '    resource: "*"',
      "    effect: allow",
      '  - action: "subagent"',
      '    resource: "*"',
      "    effect: deny",
      "---",
      "",
      "You review one task packet at a time.",
      "",
      "Check spec compliance, edge cases, and test quality. Report findings by severity with file and line references. Do not edit files and do not dispatch subagents.",
      "",
    ].join("\n");
  }

  return [
    "---",
    "description: Implements one self-contained task packet at a time",
    "mode: subagent",
    "steps: 8",
    "permissions:",
    '  - action: "edit"',
    '    resource: "*"',
    "    effect: allow",
    '  - action: "shell"',
    '    resource: "*"',
    "    effect: allow",
    '  - action: "read"',
    '    resource: "*"',
    "    effect: allow",
    '  - action: "subagent"',
    '    resource: "*"',
    "    effect: deny",
    "---",
    "",
    "You implement exactly one task packet.",
    "",
    "The packet is your complete context. Touch only the files it lists. Run its verification command before reporting. Do not read the whole repository and do not dispatch subagents.",
    "",
    "Return a short report: status, files changed, verification result, and any concern.",
    "",
  ].join("\n");
}
